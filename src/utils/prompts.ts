/** Tarih için sabit soru (aynı gün hep aynı), shift ile "başka soru" */
export function promptFor(date: string, shift = 0): string {
  let h = 0;
  for (const ch of date) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return PROMPTS[(h + shift) % PROMPTS.length];
}
